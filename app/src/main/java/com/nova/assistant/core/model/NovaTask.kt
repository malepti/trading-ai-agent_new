package com.nova.assistant.core.model

import java.util.UUID

/**
 * Risk classification for Human-In-The-Loop policy enforcement.
 */
enum class RiskLevel {
    READ_ONLY,           // Category A: Launching apps, reading visible content, search
    LOW_RISK_MUTATION,   // Category B: Typing drafts, saving local temporary notes
    HIGH_RISK_MUTATION   // Category C: Sending messages, emails, deleting files, money transfers
}

/**
 * Valid action primitives executable via Android AccessibilityService.
 */
enum class ActionType {
    LAUNCH_PACKAGE,
    CLICK_NODE,
    SET_TEXT,
    SCROLL_FORWARD,
    SCROLL_BACKWARD,
    STAGE_ACTION,
    VERIFY_STATE
}

/**
 * A single discrete action step within a multi-step execution plan.
 */
data class ActionStep(
    val stepIndex: Int,
    val actionType: ActionType,
    val targetApp: String? = null,
    val targetNodeId: String? = null,
    val targetText: String? = null,
    val payload: String? = null,
    val isCompleted: Boolean = false
)

/**
 * High-level task structure generated by Cognitive Reasoning Engine.
 */
data class NovaTask(
    val taskId: String = UUID.randomUUID().toString(),
    val intent: String,
    val targetApp: String,
    val entities: Map<String, String> = emptyMap(),
    val riskLevel: RiskLevel,
    val requiresConfirmation: Boolean,
    val stagedSummary: String,
    val steps: List<ActionStep>,
    val timestamp: Long = System.currentTimeMillis(),
    val approvalToken: String? = null,
    val isApproved: Boolean = false
)
